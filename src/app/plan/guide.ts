export function mealGuide(p: Profile): GuideSection[] {
  const dir = weightDirection(p.goal)
  return [
    {
      title: 'カロリーの決め方',
      body: [
        '基礎代謝 (年齢・身長・体重から計算) × 普段の活動量 に、その日のトレーニングで使う分を足したものが「維持カロリー」です。',
        dir === 'down'
          ? 'そこから1日あたり体重の0.5%/週ぶんを差し引いています。食べなさすぎると筋肉まで落ちるので、目安より大きく減らさないでください。'
          : dir === 'up'
            ? 'そこに筋肉が増えるペースのぶんだけ上乗せしています。急に増やしても増えるのは主に脂肪です。'
            : '維持カロリーを目安にしています。体重が2週間続けて上下するようなら、主食の量で調整してください。',
      ],
    },
    {
      title: 'PFC (タンパク質・脂質・炭水化物)',
      bullets: [
        'タンパク質: 筋肉の材料。毎食に分けてとると使われやすい',
        '脂質: ホルモンの材料なので減らしすぎない。カロリーの25%前後',
        '炭水化物: トレーニングの燃料。トレーニングの前後に多めに配分しています',
        '休養日はトレーニングで使う分が減るので、主食を少し減らした目安になります',
      ],
    },
    {
      title: '続けるコツ',
      bullets: [
        '毎日きっちり守るより、1週間の平均で目安に近ければOK',
        'まずはタンパク質の量だけ守るところから始める',
        '外食の日は、主食を少なめ・タンパク質多めのメニューを選ぶ',
      ],
    },
  ]
}

