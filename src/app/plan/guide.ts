/** いつでも守るルール (上から優先) */
export function rulesFor(p: Profile): string[] {
  const rules = [
    'フォームが崩れたらそのセットは終わり。重さより正しい動きを優先する',
    '「あと何回できるか (RIR)」の指示を守る。毎回限界まで追い込まない',
    '睡眠は7時間以上を目標に。寝不足の日は「疲れ気味」にしてメニューを軽くする',
  ]
  if (p.injuries.length) rules.push('痛みが出た種目はその場で中止し、「別のメニューにする」で入れ替える。痛みが続くときは専門家に相談')
  if (weightDirection(p.goal)) rules.push('体重は週に1〜2回、同じ条件 (朝・トイレのあと) で測る。1日の増減は水分なので気にしない')
  if (p.places.includes('box')) rules.push('CrossFit のクラスに出る日は、クラスのWODを優先。スキャンするとこの画面に表示される')
  rules.push('予定どおりにできない日があっても大丈夫。次の日からまたプランに戻ればいい')
  return rules
}

